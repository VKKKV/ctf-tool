# Find all unique characters
unique_chars = sorted(set(ciphertext))
print(f"Total unique characters: {len(unique_chars)}")
for i, c in enumerate(unique_chars):
    print(f"{i}: '{c}' (U+{ord(c):04X})")

# Count frequencies
freq = {}
for c in ciphertext:
    if c not in freq:
        freq[c] = 0
    freq[c] += 1

print("\nFrequencies (sorted):")
for c, count in sorted(freq.items(), key=lambda x: -x[1]):
    print(f"'{c}' (U+{ord(c):04X}): {count}")
